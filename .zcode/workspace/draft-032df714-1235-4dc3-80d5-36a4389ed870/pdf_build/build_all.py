H1_ORPHAN = (PAGE_H - TOP_M - BOTTOM_M) * 0.18

def add_heading(text, style, level=0):
    key = 'h_%s' % hashlib.md5(text.encode('utf-8')).hexdigest()[:8]
    p = Paragraph('<a name="%s"/>%s' % (key, text), style)
    p.bookmark_name = text
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

def h1_block(text, first_flowables):
    """H1 heading + accent rule + first content, orphan-protected."""
    rule = HRFlowable(width='100%', thickness=1.6, color=ACCENT, spaceBefore=0, spaceAfter=10)
    return [CondPageBreak(H1_ORPHAN), Spacer(1, 14),
            KeepTogether([add_heading(text, h1, level=0), rule] + first_flowables)]

def fx(txt):
    """Bind em dash to the preceding word (no line-start dashes in justified text)."""
    return txt.replace(' — ', ' — ')

def para(txt, style=None):
    return Paragraph(fx(txt), style or body)

