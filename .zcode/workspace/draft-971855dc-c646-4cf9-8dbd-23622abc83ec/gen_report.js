function tCell(text, { header = false, fill = null, alignRight = false, widthPct, small = false } = {}) {
  return new TableCell({
    width: { size: widthPct, type: WidthType.PERCENTAGE },
    margins: { top: 50, bottom: 50, left: 100, right: 100 },
    shading: fill ? { type: ShadingType.CLEAR, fill } : undefined,
    verticalAlign: VerticalAlign.CENTER,
    children: [new Paragraph({
      alignment: alignRight ? AlignmentType.RIGHT : AlignmentType.LEFT,
      spacing: { line: 264 },
      children: [new TextRun({ text: String(text), bold: header, size: small ? 17 : 19, color: header ? P.table.headerText : "000000", font: FONT })],
    })],
  });
}
function makeTable(headers, rows, widths, { small = false, zebra = true } = {}) {
  const headerRow = new TableRow({
    tableHeader: true, cantSplit: true,
    children: headers.map((t, i) => tCell(t, { header: true, fill: P.table.headerBg, widthPct: widths[i], small })),
  });
  const dataRows = rows.map((r, ri) => new TableRow({
    cantSplit: true,
    children: r.map((t, ci) => tCell(t, {
      fill: zebra && ri % 2 === 0 ? P.table.surface : "FFFFFF",
      widthPct: widths[ci], small,
      alignRight: ci > 0 && /^[\d$≈×+\-]/.test(String(t)) && String(t).length < 16,
    })),
  }));
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 4, color: P.accent },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: P.accent },
      left: NB, right: NB,
      insideHorizontal: { style: BorderStyle.SINGLE, size: 1, color: P.table.innerLine },
      insideVertical: NB,
    },
    rows: [headerRow, ...dataRows],
  });
}
